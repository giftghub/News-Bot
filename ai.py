# -----------------------------
# 경제 브리핑 생성
# -----------------------------

def make_briefing(articles):

    article_text = ""

    for article in articles:

        title = article.get("title", "")
        content = article.get("content", "")

        article_text += f"""
제목: {title}

내용:
{content}

--------------------
"""

    # -----------------------------
    # Gemini API 호출
    # -----------------------------

    max_retries = 4

    for attempt in range(1, max_retries + 1):

        try:

            print(
                f"Gemini 브리핑 생성 시도 "
                f"{attempt}/{max_retries}"
            )

            response = client.models.generate_content(
                model="gemini-3.6-flash",
                contents=SYSTEM_PROMPT + "\n\n" + article_text
            )

            print("Gemini 브리핑 생성 완료")

            return response.text

        except Exception as e:

            print(f"Gemini API 오류 발생: {e}")

            # 마지막 시도에서도 실패하면 종료
            if attempt == max_retries:

                print(
                    "Gemini API 재시도 횟수를 모두 사용했습니다."
                )

                raise

            # 지수 백오프
            wait_time = 10 * (2 ** (attempt - 1))

            print(
                f"{wait_time}초 후 Gemini API를 다시 호출합니다."
            )

            time.sleep(wait_time)


